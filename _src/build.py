#!/usr/bin/env python3
"""Build the Sudbury Workforce site.

    python3 _src/build.py

Standard library only. Reads _src/site.json (settings), _src/pages/*.html
(page content, each starting with a JSON header) and _src/image-manifest.json
(written by _src/images.py), then writes at the repo root:

    index.html, <page>/index.html, 404.html, sitemap.xml, robots.txt

GitHub Pages serves those files as they are -- nothing is built on GitHub.
Internal links and assets are relative, so the output works at the github.io
subpath, at a domain root and on a local server; 404.html is served at any
path, so it uses absolute URLs instead. All absolute URLs come from "url" in
_src/site.json.
"""

