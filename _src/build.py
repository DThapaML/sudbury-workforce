def sitemap(site, pages):
    order = ['home'] + [s['slug'] for s in site['services']]
    order += sorted(pid for pid in pages if pid not in order)
    urls = ''.join(f'  <url><loc>{esc(pages[pid].url)}</loc></url>\n' for pid in order if pages[pid].indexable)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<!-- {MARK} -->\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f'{urls}</urlset>\n')


def robots(site):
    return f'# {MARK}\nUser-agent: *\nAllow: /\n\nSitemap: {site["url"]}sitemap.xml\n'


def remove_stale(keep):
    """Delete <dir>/index.html files this script wrote earlier for pages that are gone."""
    removed = []
    for index in sorted(ROOT.glob('*/index.html')):
        if index in keep or index.parent.name.startswith(('_', '.')):
            continue
        if MARK in index.read_text(encoding='utf-8', errors='replace')[:200]:
            index.unlink()
            removed.append(rel(index))
            if not any(index.parent.iterdir()):
                index.parent.rmdir()
    return removed


def build():
    site = load_site()
    manifest = read_json(MANIFEST)
    pages = load_pages(site)
    renderer = Renderer(site, manifest, pages)
    outputs = {}
    for pid in ['home'] + [s['slug'] for s in site['services']] + sorted(pages):
        page = pages[pid]
        if page.out not in outputs:
            outputs[page.out] = renderer.render(page)
    outputs[ROOT / 'sitemap.xml'] = sitemap(site, pages)
    outputs[ROOT / 'robots.txt'] = robots(site)
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
    return list(outputs), remove_stale(set(outputs))


def main():
    try:
        written, removed = build()
    except BuildError as e:
        print(f'build failed: {e}', file=sys.stderr)
        return 1
    for path in written:
        print(rel(path))
    for path in removed:
        print(f'removed {path} (its page is gone)')
    pages = sum(1 for p in written if p.suffix == '.html')
    print(f'{len(written)} files written: {pages} HTML pages, sitemap.xml, robots.txt')
    return 0


if __name__ == '__main__':
    sys.exit(main())
