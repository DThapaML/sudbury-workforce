    def jsonld(self):
        page, site, biz = self.page, self.site, self.biz
        business_id = site['url'] + '#business'
        graph = [{
            '@type': 'HomeAndConstructionBusiness',
            '@id': business_id,
            'name': biz['name'],
            'url': site['url'],
            'logo': self.absolute(self.manifest['logo']['variants'][-1]['fallback']),
            'image': self.absolute(self.image(site['og_image'])['og']['src']),
            'telephone': phone_ld(biz['phone']),
            'email': biz['email'],
            'address': {
                '@type': 'PostalAddress',
                'addressLocality': biz['city'],
                'addressRegion': biz['region'],
                'addressCountry': biz['country'],
            },
            'areaServed': self.places_ld(),
        }]
        svc = self.service_by_slug.get(page.meta.get('service'))
        if svc and page.indexable:
            graph.append({
                '@type': 'Service',
                '@id': page.url + '#service',
                'name': page.name,
                'serviceType': svc['name'],
                'description': page.meta['description'],
                'url': page.url,
                'provider': {'@id': business_id},
                'areaServed': self.places_ld(page.meta.get('area_served'), everywhere=False),
            })
        if page.indexable and not page.is_home:
            graph.append({
                '@type': 'BreadcrumbList',
                '@id': page.url + '#breadcrumb',
                'itemListElement': [
                    {'@type': 'ListItem', 'position': i, 'name': name, 'item': self.pages[pid].url}
                    for i, (name, pid) in enumerate(self.trail(), 1)],
            })
        if page.is_home:
            # Lets Google show "Sudbury Workforce" as the site name in results.
            graph.append({
                '@type': 'WebSite',
                '@id': site['url'] + '#website',
                'name': biz['name'],
                'url': site['url'],
                'publisher': {'@id': business_id},
            })
        data = {'@context': 'https://schema.org', '@graph': graph}
        return json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')

