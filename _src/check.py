# Copy the site must never contain. Checked against visible text, alt text,
# placeholders, meta tags and JSON-LD. The owner's "Affordable Rates / Fair
# pricing. No hidden fees." line is allowed and matches none of these.
BANNED = [
    ('price ($ + digits)', r'\$\s*\d'),
    ('price (dollars / CAD)', r'\b\d[\d,.]*\s*(?:dollars?|bucks|CAD|CDN)\b|\b(?:CAD|CDN)\s*\d'),
    ('price per hour', r'\bper\s+hour\b|/\s*(?:hr|hour)\b|\bhourly\s+rates?\b'),
    ('discount', r'\bdiscount'),
    ('% off', r'%\s*off\b|\bpercent\s+off\b'),
    ('coupon', r'\bcoupons?\b'),
    ('cheapest / lowest price', r'\bcheapest\b|\blowest\s+prices?\b'),
    ('insurance claim', r'\binsured\b|\binsurance\b'),
    ('WSIB claim', r'\bWSIB\b'),
    ('certification claim', r'\bcertified\b|\bcertifications?\b|\blicensed\b|\bbonded\b'),
    ('reviews or ratings', r'\breviews?\b|\brated\b|\bratings?\b|\b(?:5|five)[- ]stars?\b'),
    ('years in business', r'\byears?\s+of\s+experience\b|\b\d+\+?\s+years\b|\bsince\s+(?:19|20)\d\d\b'),
    ('guarantee', r'\bguarantee[sd]?\b'),
    ('24/7 claim', r'\b24\s*/\s*7\b'),
    ('#1 claim', r'#\s*1\b|\bnumber\s+one\b'),
    ('trusted by', r'\btrusted\s+by\b'),
    ('customer or job count', r'\b\d[\d,]*\+?\s+(?:happy\s+|satisfied\s+)?(?:customers?|clients?|jobs?)\b'),
    ('service not on the list', r'\broofs?\b|\bcamps?\b|\bjunk\b'),
    ('place outside Greater Sudbury', r'\b(?:Toronto|Ottawa|Mississauga|Barrie|Timmins|North Bay|Sault Ste\.? Marie'
                                      r'|SSM|Espanola|Elliot Lake|Manitoulin|Parry Sound|Markstay|Massey)\b'),
]
FORBIDDEN_LD_KEYS = {'aggregateRating', 'review', 'reviews', 'priceRange', 'offers', 'foundingDate', 'award'}

VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr'}


def rel(path):
    return path.relative_to(ROOT).as_posix()


class Parsed(HTMLParser):
    """Collects what the checks need from one generated page."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []
        self.sections_in_main = 0
        self.picture = None
        self.capture = None
        self.buffer = []
        self.comments = []
        self.title = None
        self.meta = {}
        self.canonical = []
        self.stylesheets = []
        self.anchors = []
        self.assets = []
        self.ids = []
        self.h1s = []
        self.imgs = []
        self.videos = []
        self.jsonld = []
        self.forms = []
        self.options = []
        self.eyebrows = []
        self.text = []
        self.attr_text = []

    def flags(self):
        found = set()
        for _, flags in self.stack:
            found |= flags
        return found

    def handle_starttag(self, tag, attrs):
        a = {k: (v if v is not None else '') for k, v in attrs}
        classes = a.get('class', '').split()
        flags = set()
        if tag == 'header':
            flags.add('header')
        if tag == 'footer':
            flags.add('footer')
        if tag == 'nav' and 'mobile-bar' in classes:
            flags.add('mobile-bar')
        if tag == 'section' and self.stack and self.stack[-1][0] == 'main':
            self.sections_in_main += 1
            if self.sections_in_main == 1:
                flags.add('hero')
        if 'id' in a:
            self.ids.append(a['id'])
        for name in ('alt', 'aria-label', 'placeholder', 'title'):
            if a.get(name):
                self.attr_text.append(a[name])
        where = self.flags() | flags

        if tag == 'title':
            self.capture, self.buffer = 'title', []
        elif tag == 'h1':
            self.capture, self.buffer = 'h1', []
        elif tag == 'p' and 'eyebrow' in classes:
            self.capture, self.buffer = 'eyebrow', []
        elif tag == 'option':
            self.capture, self.buffer = 'option', []
        elif tag == 'meta':
            key = a.get('name') or a.get('property')
            if key:
                self.meta[key] = a.get('content', '')
                if key == 'description' or key.startswith(('og:', 'twitter:')):
                    self.attr_text.append(a.get('content', ''))
        elif tag == 'link':
            rels = a.get('rel', '').split()
            if 'canonical' in rels:
                self.canonical.append(a.get('href', ''))
            elif 'stylesheet' in rels:
                self.stylesheets.append(a.get('href', ''))
                self.assets.append(a.get('href', ''))
            elif 'icon' in rels or 'apple-touch-icon' in rels:
                self.assets.append(a.get('href', ''))
        elif tag == 'a':
            self.anchors.append((a.get('href'), where, a))
        elif tag == 'picture':
            self.picture = {'sources': []}
        elif tag == 'source':
            if self.picture is not None:
                self.picture['sources'].append(a)
            self.assets += srcset_urls(a.get('srcset', ''))
            if a.get('src'):
                self.assets.append(a['src'])
        elif tag == 'img':
            self.imgs.append({'attrs': a, 'where': where, 'picture': self.picture})
            if a.get('src'):
                self.assets.append(a['src'])
            self.assets += srcset_urls(a.get('srcset', ''))
        elif tag == 'video':
            self.videos.append({'attrs': a, 'where': where})
            for name in ('src', 'poster', 'data-src'):
                if a.get(name):
                    self.assets.append(a[name])
        elif tag == 'script':
            if a.get('type') == 'application/ld+json':
                self.capture, self.buffer = 'jsonld', []
            else:
                self.capture, self.buffer = 'script', []
                if a.get('src'):
                    self.assets.append(a['src'])
        elif tag == 'style':
            self.capture, self.buffer = 'style', []
        elif tag == 'form':
            self.forms.append(a)

        if tag not in VOID:
            self.stack.append((tag, flags))

    def handle_endtag(self, tag):
        if tag == 'picture':
            self.picture = None
        if self.capture and tag in ('title', 'h1', 'p', 'option', 'script', 'style'):
            text = ''.join(self.buffer)
            kind, self.capture = self.capture, None
            if kind == 'title':
                self.title = text.strip()
            elif kind == 'h1':
                self.h1s.append(' '.join(text.split()))
            elif kind == 'eyebrow':
                self.eyebrows.append(' '.join(text.split()))
            elif kind == 'option':
                self.options.append(text.strip())
            elif kind == 'jsonld':
                self.jsonld.append(text)
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i][0] == tag:
                del self.stack[i:]
                break

    def handle_data(self, data):
        if self.capture:
            self.buffer.append(data)
        if self.capture not in ('script', 'style', 'jsonld'):
            self.text.append(data)

    def handle_comment(self, data):
        self.comments.append(data.strip())


def srcset_urls(srcset):
    return [part.strip().split()[0] for part in srcset.split(',') if part.strip()]


def strings_in(value):
    """Every string inside a JSON value."""
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for v in value.values():
            yield from strings_in(v)
    elif isinstance(value, list):
        for v in value:
            yield from strings_in(v)


def keys_in(value):
    if isinstance(value, dict):
        for k, v in value.items():
            yield k
            yield from keys_in(v)
    elif isinstance(value, list):
        for v in value:
            yield from keys_in(v)


class Checker:
    def __init__(self):
        self.problems = []
        self.site = json.loads((SRC / 'site.json').read_text(encoding='utf-8'))
        self.manifest = json.loads((SRC / 'image-manifest.json').read_text(encoding='utf-8'))
        self.url = self.site['url']
        self.biz = self.site['business']
        self.services = {s['slug']: s for s in self.site['services']}
        self.places = [p for g in self.site['areas'] for p in g['places']]
        self.places += [n for g in self.site['areas'] for n in g.get('neighbourhoods', [])]
        self.place_words = ['Sudbury'] + self.places
        self.tel_main = 'tel:+' + self.digits(self.biz['phone'])
        self.tel_second = 'tel:+' + self.digits(self.biz['phone_second'])
        self.pages = {}       # output path -> page id
        for src in sorted((SRC / 'pages').glob('*.html')):
            pid = src.stem
            out = 'index.html' if pid == 'home' else '404.html' if pid == '404' else f'{pid}/index.html'
            self.pages[out] = pid
        self.parsed = {}

    @staticmethod
    def digits(phone):
        d = re.sub(r'\D', '', phone)
        return d if len(d) == 11 else '1' + d

    def problem(self, where, message):
        self.problems.append(f'{where}: {message}')

    # ---- url helpers

    def page_url(self, out):
        if out == 'index.html':
            return self.url
        if out == '404.html':
            return self.url + '404.html'
        return self.url + out[:-len('index.html')]

    def local(self, absolute):
        """Repo file an absolute site URL is served from, or None if not on this site."""
        parts = urlsplit(absolute)
        bare = parts._replace(query='', fragment='').geturl()
        if not bare.startswith(self.url):
            return None
        rest = unquote(bare[len(self.url):])
        if rest == '' or rest.endswith('/'):
            rest += 'index.html'
        return rest

    def resolve(self, out, ref, what, fragment_ok=True):
        """Check one link or asset reference from page `out`."""
        if ref is None or ref == '':
            self.problem(out, f'empty {what} reference')
            return
        is_404 = out == '404.html'
        if ref.startswith('#'):
            if not fragment_ok:
                self.problem(out, f'{what} "{ref}" is only a fragment')
            elif ref[1:] not in self.parsed[out].ids:
                self.problem(out, f'{what} "{ref}" has no matching id on this page')
            return
        if ref.startswith(('http://', 'https://', '//')) and not ref.startswith(self.url):
            self.problem(out, f'unexpected external {what} "{ref}"')
            return
        if is_404 and not ref.startswith(self.url):
            self.problem(out, f'{what} "{ref}" must be absolute: 404.html is served at any path')
            return
        if not is_404 and (ref.startswith(self.url) or ref.startswith('/')):
            self.problem(out, f'{what} "{ref}" must be relative so the site works at any address')
            return
        # 404.html is served at unknown, deep paths: resolve its links from one.
        base = self.url + 'no/such/page' if is_404 else self.page_url(out)
        absolute = urljoin(base, ref)
        path = self.local(absolute)
        if path is None:
            self.problem(out, f'{what} "{ref}" points outside the site')
            return
        if any(part.startswith(('_', '.')) for part in path.split('/')):
            self.problem(out, f'{what} "{ref}" points at {path}, which GitHub Pages does not publish')
            return
        if not (ROOT / path).is_file():
            self.problem(out, f'{what} "{ref}" does not resolve (no {path})')
            return
        fragment = urlsplit(absolute).fragment
        if fragment:
            target = self.parsed.get(path)
            if target is None or fragment not in target.ids:
                self.problem(out, f'{what} "{ref}": no id "{fragment}" in {path}')

    # ---- checks

    def run(self):
        root_files = {p.name for p in ROOT.iterdir()}
        if '.nojekyll' in root_files:
            self.problem('.nojekyll', 'must not exist: it would make GitHub Pages publish _src/')
        if 'README.md' in root_files:
            self.problem('README.md', 'a root README.md is rendered as a page by GitHub Pages; keep docs in _src/')
        for out in self.pages:
            path = ROOT / out
            if not path.is_file():
                self.problem(out, 'missing -- run python3 _src/build.py')
                continue
            parser = Parsed()
            parser.feed(path.read_text(encoding='utf-8'))
            parser.close()
            self.parsed[out] = parser
        for index in sorted(ROOT.glob('*/index.html')):
            out = rel(index)
            if out not in self.pages and MARK in index.read_text(encoding='utf-8', errors='replace')[:200]:
                self.problem(out, 'generated page with no source in _src/pages/ -- rebuild to remove it')

        titles, descriptions = {}, {}
        for out, page in self.parsed.items():
            self.check_page(out, page)
            titles.setdefault(page.title, []).append(out)
            descriptions.setdefault(page.meta.get('description'), []).append(out)
        for label, seen in (('title', titles), ('meta description', descriptions)):
            for value, outs in seen.items():
                if value and len(outs) > 1:
                    self.problem(', '.join(outs), f'share the same {label}')
        if 'index.html' in self.parsed:
            self.check_home(self.parsed['index.html'])
        self.check_job_photos()
        self.check_sitemap()
        self.check_robots()
        self.check_video_files()
        self.check_masters()
        return self.problems

    def check_page(self, out, page):
        pid = self.pages[out]
        is_404 = pid == '404'
        if not page.comments or page.comments[0] != MARK:
            self.problem(out, f'first comment must be "{MARK}"')

        # One H1 that names the place.
        if len(page.h1s) != 1:
            self.problem(out, f'needs exactly one <h1>, found {len(page.h1s)}')
        for h1 in page.h1s:
            if not any(word in h1 for word in self.place_words):
                self.problem(out, f'H1 "{h1}" names neither Sudbury nor an area')
        svc = self.services.get(pid)
        if svc and page.h1s and svc['name'].lower() not in page.h1s[0].lower():
            self.problem(out, f'H1 "{page.h1s[0]}" does not name the service "{svc["name"]}"')

        # Title and description.
        title = page.title or ''
        description = page.meta.get('description', '')
        if not title:
            self.problem(out, 'missing <title>')
        elif len(title) > TITLE_MAX:
            self.problem(out, f'title is {len(title)} characters (max {TITLE_MAX}): "{title}"')
        if not description:
            self.problem(out, 'missing meta description')
        elif len(description) > DESCRIPTION_MAX:
            self.problem(out, f'meta description is {len(description)} characters (max {DESCRIPTION_MAX})')
        if not is_404:
            lead = title.split(' | ')[0]
            if lead.startswith(self.biz['name']) or not any(w in lead for w in self.place_words):
                self.problem(out, f'title should lead with the service and Sudbury or the area: "{title}"')
            first = re.split(r'[.:]\s', description, maxsplit=1)[0]
            if description.startswith(self.biz['name']) or not any(w in first for w in self.place_words):
                self.problem(out, 'meta description should lead with the service and Sudbury or the area')

        # Canonical, robots, Open Graph.
        expected = self.page_url(out)
        if is_404:
            if page.canonical:
                self.problem(out, 'the 404 page must not have a canonical link')
            if 'noindex' not in page.meta.get('robots', ''):
                self.problem(out, 'the 404 page needs <meta name="robots" content="noindex">')
        elif page.canonical != [expected]:
            self.problem(out, f'canonical should be exactly one link to {expected}, found {page.canonical}')
        for key in ('og:title', 'og:description', 'og:image', 'og:image:alt', 'twitter:card'):
            if not page.meta.get(key):
                self.problem(out, f'missing <meta> {key}')
        if (page.meta.get('og:image:width'), page.meta.get('og:image:height')) != ('1200', '630'):
            self.problem(out, 'og:image must be declared 1200x630')
        og_image = page.meta.get('og:image', '')
        path = self.local(og_image)
        if not path or not (ROOT / path).is_file():
            self.problem(out, f'og:image "{og_image}" is not a file on this site')
        if not is_404 and page.meta.get('og:url') != expected:
            self.problem(out, f'og:url should be {expected}')

        # Fonts: only the weights in use.
        fonts = [s for s in page.stylesheets if 'fonts.googleapis.com' in s]
        if fonts != [FONTS_URL]:
            self.problem(out, f'Google Fonts link should be exactly {FONTS_URL}')

        self.check_jsonld(out, page, pid)
        self.check_links(out, page)
        self.check_images(out, page)
        self.check_form(out, page, pid)

        # Banned claims.
        copy = '\n'.join(page.text + page.attr_text)
        for block in page.jsonld:
            try:
                copy += '\n' + '\n'.join(strings_in(json.loads(block)))
            except json.JSONDecodeError:
                pass
        for label, pattern in BANNED:
            for match in re.finditer(pattern, copy, re.I):
                start = max(0, match.start() - 30)
                snippet = ' '.join(copy[start:match.end() + 30].split())
                self.problem(out, f'banned ({label}): "...{snippet}..."')

        dupes = sorted({i for i in page.ids if page.ids.count(i) > 1})
        if dupes:
            self.problem(out, f'duplicate ids: {", ".join(dupes)}')

    def check_jsonld(self, out, page, pid):
        nodes = []
        for block in page.jsonld:
            try:
                data = json.loads(block)
            except json.JSONDecodeError as e:
                self.problem(out, f'JSON-LD does not parse: {e}')
                continue
            if data.get('@context') != 'https://schema.org':
                self.problem(out, 'JSON-LD @context must be https://schema.org')
            nodes += data.get('@graph', [data])
            bad = FORBIDDEN_LD_KEYS & set(keys_in(data))
            if bad:
                self.problem(out, f'JSON-LD must not claim {", ".join(sorted(bad))}')
            for value in strings_in(data):
                if value.startswith('http') and not value.startswith(('https://schema.org', self.url)):
                    self.problem(out, f'JSON-LD URL "{value}" is not on {self.url}')
        types = [n.get('@type') for n in nodes]
        business_id = self.url + '#business'
        businesses = [n for n in nodes if n.get('@type') == 'HomeAndConstructionBusiness']
        if len(businesses) != 1:
            self.problem(out, f'JSON-LD needs exactly one HomeAndConstructionBusiness, found {len(businesses)}')
        for b in businesses:
            for field in ('name', 'url', 'logo', 'image', 'telephone', 'email', 'address', 'areaServed'):
                if not b.get(field):
                    self.problem(out, f'JSON-LD business is missing "{field}"')
            if b.get('@id') != business_id:
                self.problem(out, f'JSON-LD business @id should be {business_id}')
            if b.get('url') != self.url:
                self.problem(out, f'JSON-LD business url should be {self.url}')
            if b.get('telephone') != '+{0}-{1}-{2}-{3}'.format(*re.match(
                    r'(\d)(\d{3})(\d{3})(\d{4})', self.digits(self.biz['phone'])).groups()):
                self.problem(out, 'JSON-LD telephone must be the main number')
            if b.get('email') != self.biz['email']:
                self.problem(out, 'JSON-LD email must be the business email')
            address = b.get('address') or {}
            want = {'@type': 'PostalAddress', 'addressLocality': self.biz['city'],
                    'addressRegion': self.biz['region'], 'addressCountry': self.biz['country']}
            if address != want:
                self.problem(out, f'JSON-LD address must be exactly {want} (no street)')
            for field in ('logo', 'image'):
                path = self.local(b.get(field) or '')
                if not path or not (ROOT / path).is_file():
                    self.problem(out, f'JSON-LD business {field} is not a file on this site')
            if not isinstance(b.get('areaServed'), list) or not b['areaServed']:
                self.problem(out, 'JSON-LD areaServed must list the areas')
        for node in nodes:
            if node.get('@type') not in PAGE_TYPES:
                self.problem(out, f'unexpected JSON-LD type {node.get("@type")}')

        expected = self.page_url(out)
        service_page = pid in self.services
        services = [n for n in nodes if n.get('@type') == 'Service']
        if service_page and not services:
            self.problem(out, 'service pages need a JSON-LD Service')
        for s in services:
            if s.get('provider') != {'@id': business_id}:
                self.problem(out, 'JSON-LD Service provider must reference the business by @id')
            if s.get('url') != expected:
                self.problem(out, f'JSON-LD Service url should be {expected}')
            for field in ('name', 'serviceType', 'areaServed'):
                if not s.get(field):
                    self.problem(out, f'JSON-LD Service is missing "{field}"')
        crumbs = [n for n in nodes if n.get('@type') == 'BreadcrumbList']
        inner = pid not in ('home', '404')
        if inner and len(crumbs) != 1:
            self.problem(out, 'inner pages need exactly one JSON-LD BreadcrumbList')
        if not inner and crumbs:
            self.problem(out, 'only inner pages carry a BreadcrumbList')
        for crumb in crumbs:
            items = crumb.get('itemListElement', [])
            if [i.get('position') for i in items] != list(range(1, len(items) + 1)) or len(items) < 2:
                self.problem(out, 'BreadcrumbList positions must run 1, 2, ...')
            if items and (items[0].get('item') != self.url or items[-1].get('item') != expected):
                self.problem(out, 'BreadcrumbList must run from the home page to this page')
            for item in items:
                path = self.local(item.get('item', ''))
                if not item.get('name') or not path or path not in self.pages:
                    self.problem(out, f'BreadcrumbList item {item} is not a page on this site')
        websites = [n for n in nodes if n.get('@type') == 'WebSite']
        if pid == 'home':
            if len(websites) != 1 or websites[0].get('name') != self.biz['name'] or websites[0].get('url') != self.url:
                self.problem(out, 'the home page needs one JSON-LD WebSite with the business name and site url')
        elif websites:
            self.problem(out, 'only the home page carries the JSON-LD WebSite')
        if not types:
            self.problem(out, 'missing JSON-LD')

    def check_links(self, out, page):
        second_seen = 0
        for href, where, attrs in page.anchors:
            if href is None:
                self.problem(out, 'link without href')
                continue
            if href.startswith('tel:'):
                if href == self.tel_second:
                    second_seen += 1
                    if 'footer' not in where:
                        self.problem(out, f'{self.biz["phone_second"]} may only appear in the footer')
                elif href != self.tel_main:
                    self.problem(out, f'unknown phone link "{href}"')
                continue
            if href.startswith('mailto:'):
                if href != 'mailto:' + self.biz['email']:
                    self.problem(out, f'unknown email link "{href}"')
                continue
            if href.startswith('https://wa.me/'):
                parts = urlsplit(href)
                if parts.path != '/' + self.biz['whatsapp']:
                    self.problem(out, f'WhatsApp link "{href}" is not the business number')
                text = parse_qs(parts.query).get('text', [''])[0]
                if 'Page: ' not in text:
                    self.problem(out, f'WhatsApp link "{href}" should say which page it came from')
                continue
            self.resolve(out, href, 'link')
        if second_seen != 1:
            self.problem(out, f'{self.biz["phone_second"]} should appear once, as the footer\'s second number')
        header_calls = [h for h, where, a in page.anchors if 'header' in where and h == self.tel_main
                        and 'btn-call' in a.get('class', '')]
        if not header_calls:
            self.problem(out, 'header needs a Call button linking to the main number')
        bar = [h for h, where, _ in page.anchors if 'mobile-bar' in where]
        if self.tel_main not in bar or not any(h.startswith('https://wa.me/') for h in bar):
            self.problem(out, 'mobile bar needs Call and WhatsApp links')
        for ref in page.assets:
            if ref.startswith('https://fonts.googleapis.com/'):
                continue
            self.resolve(out, ref, 'asset', fragment_ok=False)

    def check_images(self, out, page):
        for img in page.imgs:
            a = img['attrs']
            label = a.get('src', '?')
            if 'alt' not in a:
                self.problem(out, f'<img> {label} has no alt attribute')
            for dim in ('width', 'height'):
                if not a.get(dim, '').isdigit():
                    self.problem(out, f'<img> {label} needs a numeric {dim}')
            picture = img['picture']
            if not picture or not any(s.get('type') == 'image/webp' for s in picture['sources']):
                self.problem(out, f'<img> {label} needs a <picture> with a WebP <source>')
            above_fold = img['where'] & {'header', 'hero'}
            if not above_fold and a.get('loading') != 'lazy':
                self.problem(out, f'<img> {label} is below the fold and should be loading="lazy"')
        for video in page.videos:
            a = video['attrs']
            if 'src' in a:
                self.problem(out, '<video> must not have a src: script.js sets it when the player is near')
            for name in ('data-src', 'poster', 'muted', 'loop', 'playsinline', 'width', 'height'):
                if name not in a:
                    self.problem(out, f'<video> needs {name}')
            if a.get('preload') != 'none':
                self.problem(out, '<video> needs preload="none"')

    def check_form(self, out, page, pid):
        forms = [f for f in page.forms if f.get('id') == 'inquiry-form']
        if len(forms) != 1:
            self.problem(out, 'every page needs the quote form (#inquiry-form)')
            return
        form = forms[0]
        if not form.get('data-page'):
            self.problem(out, 'quote form needs data-page for the WhatsApp "Page:" line')
        options = [o for o in page.options if o]
        wanted = form.get('data-service')
        if pid in self.services and wanted != self.services[pid]['form_option']:
            self.problem(out, f'quote form should preselect "{self.services[pid]["form_option"]}"')
        if wanted and wanted not in options:
            self.problem(out, f'data-service "{wanted}" is not one of the form options')
        for svc in self.services.values():
            if svc['form_option'] not in options:
                self.problem(out, f'form is missing the option "{svc["form_option"]}"')

    def check_home(self, page):
        out = 'index.html'
        for section in ('services', 'work', 'inquiry', 'contact'):
            if section not in page.ids:
                self.problem(out, f'home page lost its #{section} section')
        if not page.eyebrows or page.eyebrows[0].lower() != 'need a hand?':
            self.problem(out, 'home page needs the "Need a hand?" eyebrow above the H1')
        webp_total = fallback_total = 0
        for img in page.imgs:
            if not img['where'] & {'header', 'hero'}:
                continue
            webp = [s for s in img['picture']['sources'] if s.get('type') == 'image/webp'] if img['picture'] else []
            webp_total += self.largest(out, webp[0].get('srcset', '') if webp else img['attrs'].get('src', ''))
            fallback_total += self.largest(out, img['attrs'].get('srcset') or img['attrs'].get('src', ''))
        for label, total in (('WebP', webp_total), ('JPEG/PNG fallback', fallback_total)):
            if total > HERO_BUDGET:
                self.problem(out, f'logo + hero images ({label}, largest candidates) total '
                                  f'{total / 1024:.0f} KB, over {HERO_BUDGET // 1024} KB')
        self.hero_totals = (webp_total, fallback_total)
        for variant in self.manifest['logo']['variants']:
            for key in ('webp', 'fallback'):
                size = (ROOT / variant[key]).stat().st_size
                if size > LOGO_MAX:
                    self.problem(variant[key], f'logo file is {size / 1024:.0f} KB (max 30 KB)')

    def largest(self, out, srcset):
        best, best_w = None, -1
        for part in srcset.split(','):
            bits = part.split()
            if not bits:
                continue
            width = int(bits[1][:-1]) if len(bits) > 1 and bits[1].endswith('w') else 0
            if width > best_w:
                best, best_w = bits[0], width
        path = self.local(urljoin(self.page_url(out), best or ''))
        if not path or not (ROOT / path).is_file():
            return 0
        return (ROOT / path).stat().st_size

    def check_job_photos(self):
        images, videos = self.manifest.get('images', {}), self.manifest.get('videos', {})
        for slug, svc in self.services.items():
            out = f'{slug}/index.html'
            page = self.parsed.get(out)
            if page is None:
                continue
            used = set(page.assets)
            for key in svc['photos']:
                if key in videos:
                    files = {videos[key]['src']}
                elif key in images:
                    files = {v[k] for v in images[key]['variants'] for k in ('webp', 'fallback')}
                else:
                    self.problem(out, f'job photo "{key}" is not in the image manifest')
                    continue
                if not any(ref.split('?')[0].endswith(f) for ref in used for f in files):
                    self.problem(out, f'job photo "{key}" should appear on its service page')

    def check_sitemap(self):
        path = ROOT / 'sitemap.xml'
        if not path.is_file():
            self.problem('sitemap.xml', 'missing -- run python3 _src/build.py')
            return
        text = path.read_text(encoding='utf-8')
        if MARK not in text:
            self.problem('sitemap.xml', f'missing the "{MARK}" comment')
        try:
            tree = ET.fromstring(text)
        except ET.ParseError as e:
            self.problem('sitemap.xml', f'does not parse: {e}')
            return
        ns = '{http://www.sitemaps.org/schemas/sitemap/0.9}'
        locs = [loc.text for loc in tree.iter(f'{ns}loc')]
        want = [self.page_url(out) for out, pid in self.pages.items() if pid != '404']
        if sorted(locs) != sorted(want) or len(set(locs)) != len(locs):
            self.problem('sitemap.xml', f'should list exactly the {len(want)} pages; has {len(locs)}')

    def check_robots(self):
        path = ROOT / 'robots.txt'
        if not path.is_file():
            self.problem('robots.txt', 'missing -- run python3 _src/build.py')
            return
        text = path.read_text(encoding='utf-8')
        if MARK not in text:
            self.problem('robots.txt', f'missing the "{MARK}" comment')
        if 'User-agent: *' not in text or f'Sitemap: {self.url}sitemap.xml' not in text:
            self.problem('robots.txt', f'needs "User-agent: *" and "Sitemap: {self.url}sitemap.xml"')

    def check_video_files(self):
        if not shutil.which('ffprobe'):
            return
        for key, clip in self.manifest.get('videos', {}).items():
            result = subprocess.run(
                ['ffprobe', '-v', 'error', '-show_entries', 'stream=codec_type', '-of', 'csv=p=0',
                 str(ROOT / clip['src'])], capture_output=True, text=True)
            if 'audio' in result.stdout.split():
                self.problem(clip['src'], 'video still has an audio track')

    def check_masters(self):
        """images/opt/ is only as fresh as the masters images.py last hashed."""
        masters = self.manifest.get('masters')
        if not masters:
            self.problem('_src/image-manifest.json', 'has no master hashes -- run images.py')
            return
        for path, digest in masters.items():
            file = ROOT / path
            if not file.is_file():
                self.problem(path, 'missing since images.py ran -- run images.py')
            elif hashlib.sha1(file.read_bytes()).hexdigest() != digest:
                self.problem(path, 'changed since images.py ran -- run images.py')


def main():
    checker = Checker()
    problems = checker.run()
    for line in problems:
        print(line)
    pages = len(checker.parsed)
    totals = getattr(checker, 'hero_totals', None)
    if totals:
        print(f'home: logo + hero images {totals[0] / 1024:.0f} KB as WebP, '
              f'{totals[1] / 1024:.0f} KB as JPEG/PNG (budget {HERO_BUDGET // 1024} KB)')
    print(f'{len(problems)} problems in {pages} pages')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
